// Regenerate tests/color-budget.json from the code as it stands.
// v0.9.1154 — run this ONLY after a sweep that legitimately lowers counts:
//     node tests/update-color-budget.js
// It refuses to raise any file's budget, so it cannot be used to launder a
// new hardcoded color past the ratchet. Raising a budget has to be a
// deliberate hand edit with a reason, which is the point.
'use strict';

const fs = require('fs');
const path = require('path');
const { countAll } = require('./color-count');

const APP = path.join(__dirname, '..', 'app');
const BUDGET = path.join(__dirname, 'color-budget.json');

const now = countAll(APP);
let prev = {};
try { prev = JSON.parse(fs.readFileSync(BUDGET, 'utf8')).budgets || {}; } catch (e) {}

const next = {};
const raised = [];
const lowered = [];
Object.keys(now).sort().forEach(function (f) {
  const before = (f in prev) ? prev[f] : Infinity;
  if (now[f] > before) { raised.push(f + ': ' + before + ' → ' + now[f]); next[f] = before; }
  else { next[f] = now[f]; if (before !== Infinity && now[f] < before) lowered.push(f + ': ' + before + ' → ' + now[f]); }
});
// A file that dropped to zero keeps a 0 budget so it can never regress.
Object.keys(prev).forEach(function (f) { if (!(f in next)) next[f] = 0; });

const total = Object.keys(next).reduce(function (a, f) { return a + next[f]; }, 0);
fs.writeFileSync(BUDGET, JSON.stringify({
  _comment: 'Max hardcoded color literals per file. Generated by tests/update-color-budget.js. ' +
            'A budget may only ever go DOWN — the ratchet in the test suite enforces it. ' +
            'Palette definitions in app.css theme scopes are excluded by the counter.',
  total: total,
  budgets: next,
}, null, 2) + '\n');

console.log('budget written — total ' + total);
if (lowered.length) console.log('lowered:\n  ' + lowered.join('\n  '));
if (raised.length) {
  console.log('\nREFUSED to raise (fix these or edit the budget by hand, with a reason):\n  ' + raised.join('\n  '));
  process.exit(1);
}
