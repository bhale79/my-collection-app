// Regenerate tests/color-budget.json from the code as it stands.
// v0.9.1154 — run this ONLY after a sweep that legitimately lowers counts:
//     node tests/update-color-budget.js
// It refuses to raise any file's budget, so it cannot be used to launder a
// new hardcoded color past the ratchet.
//
// v0.9.1293 — there is now ONE way to raise budgets, and it leaves a mark:
//     node tests/update-color-budget.js --rebaseline "why"
// The reason is required and is written into the budget file itself, so the
// jump is never anonymous. This exists because the counter was FIXED, not
// because the app got worse: the old comment-stripper was a regex that read
// `accept="image/*"` as a comment opener and blanked the rest of the file,
// hiding 391 color literals — 233 of them in wizard.js alone, which was
// being counted at 4% of its real size. Rebaselining records what was
// always there. Do not reach for this flag to make a red gate go green.
'use strict';

const fs = require('fs');
const path = require('path');
const { countAll } = require('./color-count');

const APP = path.join(__dirname, '..', 'app');
const BUDGET = path.join(__dirname, 'color-budget.json');

// --rebaseline "reason" — the only way a budget goes up, and it is recorded.
const argv = process.argv.slice(2);
const rbAt = argv.indexOf('--rebaseline');
const REBASELINE = rbAt !== -1;
const REASON = REBASELINE ? String(argv[rbAt + 1] || '').trim() : '';
if (REBASELINE && REASON.length < 20) {
  console.log('--rebaseline needs a reason, in quotes, of at least 20 characters.\n' +
              'It is written into the budget file. An unexplained jump in this ' +
              'number is indistinguishable from a regression.');
  process.exit(1);
}

const now = countAll(APP);
let prevFile = {};
try { prevFile = JSON.parse(fs.readFileSync(BUDGET, 'utf8')); } catch (e) {}
const prev = prevFile.budgets || {};

const next = {};
const raised = [];
const lowered = [];
Object.keys(now).sort().forEach(function (f) {
  const before = (f in prev) ? prev[f] : Infinity;
  if (now[f] > before) {
    raised.push(f + ': ' + before + ' → ' + now[f]);
    next[f] = REBASELINE ? now[f] : before;
  }
  else { next[f] = now[f]; if (before !== Infinity && now[f] < before) lowered.push(f + ': ' + before + ' → ' + now[f]); }
});
// A file that dropped to zero keeps a 0 budget so it can never regress.
Object.keys(prev).forEach(function (f) { if (!(f in next)) next[f] = 0; });

const total = Object.keys(next).reduce(function (a, f) { return a + next[f]; }, 0);

// The rebaseline log is append-only. Every raise this file has ever taken
// stays visible, so "the budget went up" can always be traced to a stated
// reason rather than a quiet edit.
const log = Array.isArray(prevFile._rebaselines) ? prevFile._rebaselines.slice() : [];
if (REBASELINE && raised.length) {
  log.push({
    date: new Date().toISOString().slice(0, 10),
    reason: REASON,
    raised: raised,
  });
}

fs.writeFileSync(BUDGET, JSON.stringify({
  _comment: 'Max hardcoded color literals per file. Generated by tests/update-color-budget.js. ' +
            'A budget may only ever go DOWN — the ratchet in the test suite enforces it. ' +
            'Palette definitions in app.css theme scopes are excluded by the counter. ' +
            'The one exception is --rebaseline "reason", which is logged in _rebaselines below.',
  total: total,
  _rebaselines: log,
  budgets: next,
}, null, 2) + '\n');

console.log('budget written — total ' + total);
if (lowered.length) console.log('lowered:\n  ' + lowered.join('\n  '));
if (raised.length && REBASELINE) {
  console.log('\nREBASELINED (logged in the budget file):\n  ' + raised.join('\n  ') +
              '\n  reason: ' + REASON);
}
if (raised.length && !REBASELINE) {
  console.log('\nREFUSED to raise (fix these, or re-run with --rebaseline "reason"):\n  ' +
              raised.join('\n  '));
  process.exit(1);
}
